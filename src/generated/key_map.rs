//! Exact BO4E wire-key ↔ Rust snake_case field-name mapping.
//!
//! Used by `crate::json::key_transform` to convert JSON keys for
//! `to_json_snake_case` / `from_json_snake_case`. Every table is sorted by
//! its first element so lookups can binary-search, and every entry is
//! `&'static str`, so a hit never allocates.
//!
//! Only pairs whose two sides differ are listed in the two mapping tables;
//! any key absent from them maps to itself. Underscore-prefixed BO4E
//! metadata keys (`_typ`, `_version`, `_id`) are deliberately absent so they
//! survive verbatim in every mode.
//!
//! `KNOWN_FIELD_KEYS` is the separate question of whether a key is a schema
//! field *at all*, which is what stops the transform from descending into
//! somebody else's JSON.
